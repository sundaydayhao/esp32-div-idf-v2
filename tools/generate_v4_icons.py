#!/usr/bin/env python3
"""Generate 32x32 V4 firmware icons from the existing 16x16 icon.h bitmaps."""

from __future__ import annotations

import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
ICON_H = ROOT / "main" / "include" / "icon.h"
OUT_H = ROOT / "main" / "include" / "icon_v4.h"


ICON_RE = re.compile(
    r"// '([^']+)',\s*(\d+)x(\d+)px\s*"
    r"const unsigned char\s+([A-Za-z0-9_]+)\s*\[\]\s+PROGMEM\s*=\s*\{"
    r"(.*?)"
    r"\};",
    re.S,
)


def parse_bytes(body: str) -> list[int]:
    return [int(x, 16) for x in re.findall(r"0x([0-9a-fA-F]{2})", body)]


def unpack_1bpp(data: list[int], width: int, height: int) -> list[list[int]]:
    row_bytes = (width + 7) // 8
    rows: list[list[int]] = []
    for y in range(height):
        row: list[int] = []
        for x in range(width):
            b = data[y * row_bytes + x // 8]
            row.append((b >> (7 - (x % 8))) & 1)
        rows.append(row)
    return rows


def pack_1bpp(rows: list[list[int]]) -> list[int]:
    width = len(rows[0])
    row_bytes = (width + 7) // 8
    data: list[int] = []
    for row in rows:
        for byte_i in range(row_bytes):
            v = 0
            for bit in range(8):
                x = byte_i * 8 + bit
                if x < width and row[x]:
                    v |= 1 << (7 - bit)
            data.append(v)
    return data


def scale_2x(rows: list[list[int]]) -> list[list[int]]:
    out: list[list[int]] = []
    for row in rows:
        wide = [px for px in row for _ in range(2)]
        out.append(wide)
        out.append(wide.copy())
    return out


def format_bytes(data: list[int], indent: str = "  ") -> str:
    lines = []
    for i in range(0, len(data), 12):
        chunk = ", ".join(f"0x{x:02x}" for x in data[i : i + 12])
        suffix = "," if i + 12 < len(data) else ""
        lines.append(f"{indent}{chunk}{suffix}")
    return "\n".join(lines)


def main() -> None:
    text = ICON_H.read_text(encoding="utf-8", errors="ignore")
    icons = []
    for label, w_s, h_s, symbol, body in ICON_RE.findall(text):
        width = int(w_s)
        height = int(h_s)
        if width != 16 or height != 16:
            continue
        data = parse_bytes(body)
        rows = unpack_1bpp(data, width, height)
        scaled = pack_1bpp(scale_2x(rows))
        icons.append((label, symbol, scaled))

    out = [
        "#pragma once",
        "",
        "// Generated by tools/generate_v4_icons.py from 16x16 icons in icon.h.",
        "// These 32x32 aliases are used only for ESP32-DIV V4 builds.",
        "",
    ]
    for label, symbol, data in icons:
        out.append(f"// '{label}', 32x32px")
        out.append(f"const unsigned char {symbol}_v4 [] PROGMEM = {{")
        out.append(format_bytes(data))
        out.append("};")
        out.append("")

    out.append("#if defined(BOARD_ESP32_DIV_V4)")
    for _label, symbol, _data in icons:
        out.append(f"#define {symbol} {symbol}_v4")
    out.append("#endif")
    out.append("")

    OUT_H.write_text("\n".join(out), encoding="utf-8")
    print(f"Generated {OUT_H} with {len(icons)} icons")


if __name__ == "__main__":
    main()
